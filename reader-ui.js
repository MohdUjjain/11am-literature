/* Search, tabbed navigation, revision visibility and optional resume.
 * UI-only enhancement. Never edits source notes or the PDF compositor.
 */
(function () {
  'use strict';
  var STORE_VISIBILITY = '11am-literature-show-revisions-v1';
  var STORE_POSITION = '11am-literature-reading-position-v1';
  var $ = function (id) {return document.getElementById(id);};
  var chapterList = [];
  var lastHit = null, lastHitTimer = null;
  var visibilityInput = null;
  var resumeButtons = [];
  var lastCapturedAt = 0, resumeNavigatingUntil = 0;
  var searchEntries = null, results = [], shown = 0, searchTimer = null;
  var searchBox = null, searchResults = null, closeSearchButton = null;
  var searchToggle = null, searchHeader = null;
  var pageSize = 24;
  var renderedQuery = '';

  function getStored(key) {
    try {return window.localStorage.getItem(key);} catch (_) {return null;}
  }
  function setStored(key,value) {
    try {window.localStorage.setItem(key,value);} catch (_) {}
  }
  // A temporary reveal does not change the reader's saved hide preference.
  function revealRevisionTarget(target) {
    var revision = target && target.closest && target.closest('.revision-zone');
    if (!revision || visibleRevisions()) return false;
    revision.classList.add('lit-temporary-revision');
    window.dispatchEvent(new Event('resize'));
    return true;
  }
  function visibleAnchor(ch, line) {
    var chosen = null;
    // Stable scholarly identifiers survive changing font metrics and the
    // screen-only hiding/showing of revision summaries.
    var candidates = ch.querySelectorAll('.section[id], .passage[data-anchor]');
    Array.prototype.forEach.call(candidates, function(el) {
      if (!el.getClientRects().length) return;
      var top = el.getBoundingClientRect().top + window.scrollY;
      if (top <= line + 2) chosen = el;
    });
    if (!chosen) return ch.querySelector('.chapter-title-page') || ch;
    return chosen;
  }
  function anchorDescription(el,ch) {
    if (el === ch) return {kind:'chapter',key:ch.id||'',ratio:0};
    var rect = el.getBoundingClientRect();
    var probe = window.innerHeight * .36;
    var opener=el.classList.contains('chapter-title-page');
    return {
      kind:opener ? 'opener' : el.hasAttribute('data-anchor') ? 'passage' : 'section',
      key:opener ? 'opener' : el.getAttribute('data-anchor') || el.id,
      ratio:Math.max(0,Math.min(1,(probe-rect.top)/Math.max(1,rect.height)))
    };
  }
  function locateAnchor(saved) {
    if (!saved || !saved.anchor || !saved.anchor.key) return saved.chapter;
    var anchor = saved.anchor;
    if (anchor.kind==='opener')
      return saved.chapter.querySelector('.chapter-title-page') || saved.chapter;
    if (anchor.kind==='passage') {
      // Stored passage names are generated by the dossier; validate before
      // interpolation into the local CSS selector.
      if (!/^[\w-]+$/.test(anchor.key)) return saved.chapter;
      return saved.chapter.querySelector('[data-anchor="' + anchor.key + '"]') ||
             saved.chapter;
    }
    if (anchor.kind==='section') {
      var node = document.getElementById(anchor.key);
      return node && saved.chapter.contains(node) ? node : saved.chapter;
    }
    return saved.chapter;
  }
  function syncAnchorOffsets(){
    var header = $('reading-header');
    var size = header ? Math.ceil(header.getBoundingClientRect().height) + 14 : 72;
    document.documentElement.style.setProperty('--lit-header-offset',size+'px');
  }
  function collect() {
    chapterList = Array.prototype.slice.call(
      document.querySelectorAll('#book > .chapter')
    );
  }
  function visibleRevisions(){
    return getStored(STORE_VISIBILITY) !== 'false';
  }
  function showRevisions(show,store) {
    document.body.classList.toggle('lit-revisions-hidden',!show);
    if (visibilityInput) visibilityInput.checked = !!show;
    if (store) {
      document.querySelectorAll('.lit-temporary-revision').forEach(function(el){
        el.classList.remove('lit-temporary-revision');
      });
      setStored(STORE_VISIBILITY,show ? 'true' : 'false');
    }
    // Recompute progress and passage-note geometry after hiding/showing zones.
    window.dispatchEvent(new Event('resize'));
  }
  function initTabs(){
    var tabs = Array.prototype.slice.call(document.querySelectorAll('.panel-tab'));
    var panes = {
      index:$('panel-index'),
      tools:$('panel-tools')
    };
    function activate(name,focus) {
      var drawer = $('side-panel');
      if (drawer) drawer.scrollTop = 0;
      tabs.forEach(function(tab) {
        var selected = tab.getAttribute('data-tab') === name;
        tab.setAttribute('aria-selected',selected?'true':'false');
        tab.tabIndex = selected ? 0 : -1;
        if (selected && focus) tab.focus();
      });
      Object.keys(panes).forEach(function(key){
        if (panes[key]) panes[key].hidden = (name !== key);
      });
    }
    tabs.forEach(function(tab){
      tab.addEventListener('click',function(){activate(tab.getAttribute('data-tab'),false);});
      tab.addEventListener('keydown',function(event){
        if (['ArrowLeft','ArrowRight','Home','End'].indexOf(event.key)<0) return;
        event.preventDefault();
        var current = tabs.indexOf(tab);
        var next = event.key==='Home'?0:event.key==='End'?tabs.length-1:
                   (current+(event.key==='ArrowRight'?1:-1)+tabs.length)%tabs.length;
        activate(tabs[next].getAttribute('data-tab'),true);
      });
    });
    activate('index',false);
  }
  function readCheckpoint(){
    var raw = getStored(STORE_POSITION);
    if (!raw) return null;
    try {
      var parsed = JSON.parse(raw);
      if (!parsed || !/^\d+$/.test(String(parsed.chapter))) return null;
      var chapter = chapterList.find(function(ch){
        return ch.getAttribute('data-chapter') === String(parsed.chapter);
      });
      if (!chapter) return null;
      var checkpoint = {
        chapter:chapter, number:String(parsed.chapter),
        revision:!!parsed.revision, savedAt:parsed.savedAt||0, anchor:null
      };
      if(parsed.version===2 && parsed.anchor &&
         typeof parsed.anchor.key==='string' &&
         ['passage','section','opener','chapter'].indexOf(parsed.anchor.kind)>=0 &&
         Number.isFinite(parsed.anchor.ratio)){
        checkpoint.anchor={
          kind:parsed.anchor.kind,key:parsed.anchor.key,
          ratio:Math.max(0,Math.min(1,parsed.anchor.ratio))
        };
      }
      // Backwards compatibility with checkpoints created by the previous
      // height-percentage version. Converted to stable anchors on next scroll.
      if (!checkpoint.anchor && Number.isFinite(parsed.fraction))
        checkpoint.legacyFraction=Math.max(0,Math.min(1,parsed.fraction));
      return checkpoint;
    }catch(_){return null;}
  }
  function updateResumeControls() {
    var saved = readCheckpoint();
    var anchor = saved && locateAnchor(saved);
    var description = saved && anchor && anchor.closest && anchor.closest('.section');
    var heading = description && description.querySelector(':scope > h2');
    resumeButtons.forEach(function(button){
      button.disabled = !saved;
      var label=button.querySelector && button.querySelector('.reader-resume-label');
      var caption=saved ? 'Continue Reading ' + saved.number : 'Continue Reading';
      if(label) label.textContent=caption;
      else button.textContent='↪ '+caption; // Supports older copies with no icon span.
    });
    Array.prototype.forEach.call(document.querySelectorAll('.reader-resume-caption'),
      function(caption){
        caption.textContent = saved
          ? 'Reading ' + saved.number +
            (heading ? ' · ' + heading.textContent.trim() : '') +
            ' · saved on this device.'
          : 'Your reading position will be saved on this device.';
      });
  }
  function recordPosition(force){
    // When browser print CSS hides #book, rects collapse. Never let a print
    // event replace the last genuine checkpoint with the final chapter.
    if (window.matchMedia && window.matchMedia('print').matches) return;
    var now=Date.now();
    if (now<resumeNavigatingUntil) return;
    if (!force && now-lastCapturedAt<1200) return;
    var line=window.scrollY+window.innerHeight*.36;
    var active=null;
    chapterList.forEach(function(ch){
      if(ch.getClientRects().length &&
         ch.getBoundingClientRect().top+window.scrollY <= line) active=ch;
    });
    if(!active) return; // Preserve checkpoint while viewing the cover.
    var anchor=visibleAnchor(active,line);
    var revision=active.querySelector('.revision-zone');
    var inRevision=!!(revision && revision.getClientRects().length &&
      revision.getBoundingClientRect().top <= window.innerHeight*.36);
    setStored(STORE_POSITION,JSON.stringify({
      version:2,chapter:active.getAttribute('data-chapter'),
      anchor:anchorDescription(anchor,active),
      revision:inRevision,savedAt:now
    }));
    lastCapturedAt=now;
    updateResumeControls();
  }
  function continueReading(){
    var saved=readCheckpoint();
    if(!saved)return;
    var target=locateAnchor(saved);
    if(saved.revision && !visibleRevisions()){
      // Old percentage-only checkpoints and removed section IDs can resolve
      // to the chapter wrapper; still reveal its actual revision zone.
      var revealTarget=target.closest && target.closest('.revision-zone')
        ? target : saved.chapter.querySelector('.revision-zone');
      revealRevisionTarget(revealTarget);
    }
    // Older checkpoints without a passage/section ID retain one-time
    // approximate restoration, then become section anchored on scrolling.
    var top;
    if(Number.isFinite(saved.legacyFraction)){
      var chRect=saved.chapter.getBoundingClientRect();
      top=chRect.top+window.scrollY+
          saved.legacyFraction*chRect.height;
    }else{
      var rect=target.getBoundingClientRect();
      top=rect.top+window.scrollY+
          (saved.anchor ? saved.anchor.ratio : 0)*rect.height;
    }
    var max=Math.max(0,document.documentElement.scrollHeight-window.innerHeight);
    var destination=Math.max(0,Math.min(max,top-window.innerHeight*.36));
    resumeNavigatingUntil=Date.now()+1700;
    var close=$('panel-close');if(close)close.click();
    window.scrollTo({top:destination,behavior:
      window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches
        ? 'instant' : 'smooth'});
    if(!Number.isFinite(saved.legacyFraction)){
      // Focus the logical section without immediately moving the page again.
      var focus=target.closest && target.closest('.section[id]') || target;
      if(focus && focus.focus){
        if(!focus.hasAttribute('tabindex'))focus.setAttribute('tabindex','-1');
        focus.focus({preventScroll:true});
      }
    }
  }
  function initResume(){
    resumeButtons=Array.prototype.slice.call(
      document.querySelectorAll('.reader-resume-button')
    );
    resumeButtons.forEach(function(button){
      button.addEventListener('click',continueReading);
    });
    updateResumeControls();
    window.addEventListener('scroll',function(){recordPosition(false);},{passive:true});
    window.addEventListener('pagehide',function(){recordPosition(true);});
    document.addEventListener('visibilitychange',function(){
      if(document.visibilityState==='hidden')recordPosition(true);
    });
  }
  function initVisibility(){
    visibilityInput=$('lit-show-revisions');
    showRevisions(visibleRevisions(),false);
    // Native #fragment links need the revision content present before
    // the browser performs its default anchor scroll.
    var toc=$('toc-list');
    if(toc)toc.addEventListener('click',function(event){
      var link=event.target.closest && event.target.closest('a[href^="#"]');
      if(!link)return;
      var id=decodeURIComponent(link.getAttribute('href').slice(1));
      var target=document.getElementById(id);
      if(target)revealRevisionTarget(target);
    },true);
    if(visibilityInput) visibilityInput.addEventListener('change',function(){
      showRevisions(visibilityInput.checked,true);
    });
  }
  function ensureIndex(){
    if(!searchEntries && window.LiteratureSearch)
      searchEntries=window.LiteratureSearch.buildIndex(document);
    return searchEntries||[];
  }
  function closeResults(){
    if(searchResults) searchResults.hidden=true;
    if(searchBox) searchBox.setAttribute('aria-expanded','false');
  }
  function openResults(){
    if(searchResults) searchResults.hidden=false;
    if(searchBox) searchBox.setAttribute('aria-expanded','true');
  }
  // Direction is inferred from the first strong letter: Arabic fragments
  // read RTL; English titles containing Arabic quotations remain LTR/auto.
  function resultDirection(el,text) {
    var strong=String(text||'').match(/[A-Za-z\u0590-\u05FF\u0600-\u06FF]/);
    var arabic=strong && /[\u0600-\u06FF]/.test(strong[0]);
    var hebrew=strong && /[\u0590-\u05FF]/.test(strong[0]);
    el.setAttribute('dir',arabic||hebrew?'rtl':'auto');
    if(arabic)el.setAttribute('lang','ar');
    else if(hebrew)el.setAttribute('lang','he');
  }
  function mobileSearchMode(){
    return window.matchMedia
      ? window.matchMedia('(max-width:850px)').matches
      : window.innerWidth <= 850;
  }
  function expandMobileSearch(){
    if(!searchToggle || !searchHeader || !mobileSearchMode())return;
    searchHeader.classList.add('search-open');
    searchToggle.setAttribute('aria-expanded','true');
    searchToggle.setAttribute('aria-label','Close search');
    searchBox.focus();
  }
  function collapseMobileSearch(){
    if(!searchToggle || !searchHeader || !mobileSearchMode())return;
    searchHeader.classList.remove('search-open');
    searchToggle.setAttribute('aria-expanded','false');
    searchToggle.setAttribute('aria-label','Open search');
    closeResults();
    searchBox.blur();
  }
  function resultButton(hit){
    var entry = hit.entry;
    var button=document.createElement('button');
    button.type='button';button.className='reader-result';
    // Native buttons provide better semantics than orphan role="option"
    // controls without a corresponding listbox.
    var title=document.createElement('strong');
    title.className='reader-result-title';
    title.textContent = 'Reading ' + entry.chapter + ' · ' + entry.title;
    resultDirection(title,title.textContent);
    var section=document.createElement('span');
    section.className='reader-result-section';
    section.textContent = entry.section + (entry.revision ? ' · Revision' : '');
    resultDirection(section,section.textContent);
    var snippet=document.createElement('span');
    snippet.className='reader-result-snippet';
    var excerpt=window.LiteratureSearch.excerptMatch(entry.text,searchBox.value,190);
    if(excerpt.prefix) snippet.appendChild(document.createTextNode('…'));
    excerpt.parts.forEach(function(part) {
      if(part.match) {
        var mark=document.createElement('mark');
        mark.className='reader-result-match';
        mark.textContent=part.text;
        snippet.appendChild(mark);
      } else snippet.appendChild(document.createTextNode(part.text));
    });
    if(excerpt.suffix) snippet.appendChild(document.createTextNode('…'));
    resultDirection(snippet,snippet.textContent);
    button.appendChild(title);button.appendChild(section);button.appendChild(snippet);
    button.addEventListener('click',function(){jumpTo(hit);});
    return button;
  }
  function addMoreResults(){
    var end=Math.min(results.length,shown+pageSize);
    for(var i=shown;i<end;i++) searchResults.appendChild(resultButton(results[i]));
    shown=end;
    if(shown<results.length){
      var more=document.createElement('button');
      more.type='button';more.className='reader-search-more';
      more.textContent='Show more matches ('+(results.length-shown)+' remaining)';
      more.addEventListener('click',function(){
        more.remove();addMoreResults();
      });
      searchResults.appendChild(more);
    }
  }
  function jumpTo(hit){
    // A button created for a previous query must never navigate after typing.
    if(renderedQuery!==searchBox.value.trim()) {renderResults();return;}
    var target=hit.entry.destination || hit.entry.el;
    if(hit.entry.revision)revealRevisionTarget(target);
    if(lastHit)lastHit.classList.remove('reader-search-hit-target');
    if(lastHitTimer)clearTimeout(lastHitTimer);
    lastHit=target;
    target.classList.add('reader-search-hit-target');
    var fragment='#'+encodeURIComponent(hit.entry.anchorId || target.id);
    if(target.id && window.location && window.history &&
       window.location.hash!==fragment)
      window.history.pushState({literatureSearch:true},'',fragment);
    var reduce=window.matchMedia &&
      window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    target.scrollIntoView({behavior:reduce?'instant':'smooth',block:'center'});
    if (!target.hasAttribute('tabindex')) target.setAttribute('tabindex','-1');
    target.focus({preventScroll:true});
    closeResults();
    collapseMobileSearch();
    searchBox.blur();
    lastHitTimer=setTimeout(function(){
      target.classList.remove('reader-search-hit-target');
      if(lastHit===target)lastHit=null;
    },4800);
  }
  function renderResults(){
    if(!searchBox || !searchResults || !window.LiteratureSearch)return;
    var query=searchBox.value.trim();
    renderedQuery=query;
    closeSearchButton.hidden=!query;
    searchResults.replaceChildren();
    shown=0;
    if(!query){results=[];closeResults();return;}
    results=window.LiteratureSearch.find(ensureIndex(),query);
    var summary=document.createElement('div');
    summary.className='reader-search-summary';
    summary.setAttribute('role','status');
    summary.textContent=results.length
      ? results.length+' match'+(results.length===1?'':'es')+' across the dossier'
      : 'No matches found in the available readings';
    searchResults.appendChild(summary);
    addMoreResults();
    openResults();
  }
  function initSearch(){
    searchBox=$('reader-search-input');
    searchResults=$('reader-search-results');
    closeSearchButton=$('reader-search-close');
    searchToggle=$('reader-search-toggle');
    searchHeader=$('reading-header');
    if(!searchBox||!searchResults||!closeSearchButton||!window.LiteratureSearch)return;
    if(searchToggle) searchToggle.addEventListener('click',function(){
      if(searchHeader && searchHeader.classList.contains('search-open'))
        collapseMobileSearch();
      else expandMobileSearch();
    });
    searchBox.addEventListener('input',function(){
      if(searchTimer)clearTimeout(searchTimer);
      // Invalidate stale matches immediately, not after the debounce.
      renderedQuery='';
      results=[];
      closeResults();
      searchTimer=setTimeout(renderResults,140);
    });
    searchBox.addEventListener('focus',function(){
      if(searchBox.value.trim())renderResults();
    });
    closeSearchButton.addEventListener('click',function(){
      searchBox.value='';renderResults();searchBox.focus();
    });
    searchBox.addEventListener('keydown',function(event){
      if(event.key==='Escape'){
        event.preventDefault();closeResults();collapseMobileSearch();searchBox.blur();
      }else if(event.key==='Enter'){
        event.preventDefault();
        if(renderedQuery!==searchBox.value.trim())renderResults();
        if(results.length)jumpTo(results[0]);
      }else if(event.key==='ArrowDown'&&!searchResults.hidden){
        var first=searchResults.querySelector('.reader-result');
        if(first){event.preventDefault();first.focus();}
      }
    });
    searchResults.addEventListener('keydown',function(event){
      var buttons=Array.prototype.slice.call(
        searchResults.querySelectorAll('.reader-result,.reader-search-more')
      );
      var idx=buttons.indexOf(document.activeElement);
      if(event.key==='Escape'){
        event.preventDefault();closeResults();searchBox.focus();
      }else if(event.key==='ArrowDown'&&idx>=0){
        event.preventDefault();buttons[Math.min(idx+1,buttons.length-1)].focus();
      }else if(event.key==='ArrowUp'){
        event.preventDefault();
        if(idx<=0)searchBox.focus();
        else buttons[idx-1].focus();
      }
    });
    document.addEventListener('pointerdown',function(event){
      if(!searchResults.hidden &&
         !searchResults.contains(event.target) &&
         !searchBox.closest('.reader-search-wrap').contains(event.target))
        closeResults();
    });
    // Deep links created by the search index need their DOM IDs installed
    // before restoring the browser's initial fragment or Back/Forward.
    function followFragment() {
      var hash=window.location && window.location.hash;
      if(!hash || !/^#lit-(hit|passage)-/.test(hash))return;
      ensureIndex();
      var id;
      try {id=decodeURIComponent(hash.slice(1));}catch(_){return;}
      var target=document.getElementById(id);
      if(target) {
        revealRevisionTarget(target);
        target.scrollIntoView({block:'start',behavior:'instant'});
        if(!target.hasAttribute('tabindex'))target.setAttribute('tabindex','-1');
        target.focus({preventScroll:true});
      }
    }
    window.addEventListener('popstate',followFragment);
    window.addEventListener('hashchange',followFragment);
    if(window.location && /^#lit-(hit|passage)-/.test(window.location.hash))
      window.requestAnimationFrame(followFragment);
    document.addEventListener('keydown',function(event){
      var tag=(document.activeElement&&document.activeElement.tagName||'').toLowerCase();
      var editing=tag==='input'||tag==='textarea'||
                  (document.activeElement&&document.activeElement.isContentEditable);
      if((event.key==='/'&&!editing) ||
         ((event.ctrlKey||event.metaKey)&&event.key.toLowerCase()==='k')){
        event.preventDefault();expandMobileSearch();searchBox.focus();searchBox.select();
      }
    });
  }
  function setup(){
    collect();initTabs();initVisibility();initResume();initSearch();
    syncAnchorOffsets();
    window.addEventListener('resize',syncAnchorOffsets);
    if('ResizeObserver' in window && $('reading-header')){
      var observer=new ResizeObserver(syncAnchorOffsets);
      observer.observe($('reading-header'));
    }
  }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',setup);
  else setup();
})();
